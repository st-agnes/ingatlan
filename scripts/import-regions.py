#!/usr/bin/env python3
"""Generate county membership and the browser region choices from the KSH TSZJ XLSX.

The input is the full official structure workbook used by import-agglomerations.py.
Only Python's standard library is required; the downloaded workbook is untracked.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('ksh_agglomerations', ROOT / 'scripts/import-agglomerations.py')
ksh = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ksh)


def snapshot(source, retrieved_on):
    names = set(json.loads((ROOT / 'dist/data/settlements.json').read_text())['settlements'])
    rows = iter(ksh.read_rows(source))
    columns = {value: index for index, value in next(rows).items()}
    if not {'Név', "NUTS'16", 'Területi jelzőszám'} <= set(columns):
        raise ValueError('The full KSH TSZJ structure workbook is required.')
    membership, labels = {}, {}
    for row in rows:
        name, region = row.get(columns['Név'], ''), row.get(columns["NUTS'16"], '')
        if name in names:
            if name in membership:
                raise ValueError('Duplicate municipality: ' + name)
            membership[name] = region
        if name == 'Budapest kerületre nem bontható adatai':
            labels[region] = 'Budapest'
        elif name.endswith(' megye területre nem bontható adatai'):
            labels[region] = name.removesuffix(' megye területre nem bontható adatai') + ' vármegye'
    if set(membership) != names or len(set(membership.values())) != 20 or set(membership.values()) != set(labels):
        raise ValueError('All canonical municipalities must belong to exactly 20 counties/Budapest.')
    regions = [{'id': region, 'label': label,
                'settlements': sorted((name for name, code in membership.items() if code == region), key=ksh.sort_key)}
               for region, label in sorted(labels.items(), key=lambda item: (item[0] != 'HU110', ksh.sort_key(item[1])))]
    return {
        'schemaVersion': 1,
        'version': 'ksh-tszj-2026-' + retrieved_on,
        'source': {'title': 'KSH – Területi számjelrendszer struktúra elemei, 2026',
                   'url': ksh.SOURCE_URL, 'retrievedOn': retrieved_on,
                   'sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
                   'license': 'CC BY 4.0', 'licenseUrl': 'https://www.ksh.hu/copyright'},
        'processing': 'Municipality names matched exactly to the shared catalogue. NUTS 2016 county identifiers retained; county display labels use vármegye. Budapest remains a separate region. No geographic coordinates are included.',
        'regions': regions,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('xlsx', type=Path)
    parser.add_argument('--retrieved-on', default='2026-11-06')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = snapshot(args.xlsx, args.retrieved_on)
    choices = [{key: region[key] for key in ('id', 'label')} for region in data['regions']]
    js = ('// Generated by scripts/import-regions.py from the KSH 2026 TSZJ (CC BY 4.0).\n'
          '// See THIRD-PARTY-NOTICES.txt and docs/REGIONS.md.\n'
          'export const regions = Object.freeze(' + json.dumps(choices, ensure_ascii=False, indent=2)
          + '.map(region => Object.freeze(region)));\n')
    outputs = [(ROOT / 'backend/Otthonra.Api/Data/regions.json', json.dumps(data, ensure_ascii=False, indent=2) + '\n'),
               (ROOT / 'dist/regions-data.js', js)]
    for path, content in outputs:
        if args.check:
            if path.read_text() != content:
                raise ValueError('Generated output differs: ' + str(path))
        else:
            path.write_text(content)
    print(f'Verified {len(data["regions"])} regions covering {sum(len(r["settlements"]) for r in data["regions"])} canonical municipalities.')


if __name__ == '__main__':
    main()
